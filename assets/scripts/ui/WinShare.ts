const SPREAD = 25;                     // levels: the curve's scale (level 1 → top, ~level 30 → about 30 %)
const HARDER: Record<PlayDifficulty, number> = { Easy: 0, Hard: 6, 'Super Hard': 12 };   // lines further down
const JITTER = 2;                      // lines up or down at random

/** The line to show after winning level `levelNumber` (1-based) */
export function winShareLine(levelNumber: number, difficulty: PlayDifficulty): string {
  const last = LINES.length - 1;
  const base = last * (1 - Math.exp(-Math.max(0, levelNumber - 1) / SPREAD));
  const i = Math.round(base + (HARDER[difficulty] || 0) + (Math.random() * 2 - 1) * JITTER);
  return LINES[Math.max(0, Math.min(last, i))];
}
